"""Copy figures and result summaries from sumo/results into the website (docs/)."""
import glob
import json
import os
import shutil

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(HERE, "results")
DOCS = os.path.join(os.path.dirname(HERE), "docs")
OUT = os.path.join(DOCS, "assets", "results")
os.makedirs(OUT, exist_ok=True)

data = {}
for lvl in ("go2", "go3"):
    for d in sorted(glob.glob(os.path.join(RES, lvl, "*"))):
        name = f"{lvl}_{os.path.basename(d)}"
        for png in glob.glob(os.path.join(d, "*.png")):
            shutil.copy(png, os.path.join(OUT, f"{name}_{os.path.basename(png)}"))
        s = os.path.join(d, "summary.json")
        if os.path.exists(s):
            data[name] = json.load(open(s))
        for extra in ("decisions.json", "training.json", "decisions_1.json", "decisions_2.json", "blocked_2.json"):
            p = os.path.join(d, extra)
            if os.path.exists(p):
                data[f"{name}_{extra[:-5]}"] = json.load(open(p))
refs = os.path.join(os.path.dirname(HERE), "research", "references.json")
if os.path.exists(refs):
    data["references"] = json.load(open(refs))
with open(os.path.join(DOCS, "js", "results.js"), "w") as f:
    f.write("/* generated by sumo/tools/export_site.py */\nwindow.RESULTS = " + json.dumps(data, indent=0) + ";\n")
print("exported", len(data), "blocks;", len(os.listdir(OUT)), "figures")
